import { readFileSync, writeFileSync } from "node:fs";
type Token = { $type: string; $value: unknown };
const source = JSON.parse(readFileSync("src/ds/tokens/tokens.json", "utf8"));
function resolve(value: unknown): string {
  if (typeof value === "string" && value.startsWith("{")) {
    const token = value
      .slice(1, -1)
      .split(".")
      .reduce((node, key) => node[key], source);
    if (!token) throw new Error(`Unknown token ${value}`);
    return resolve(token.$value);
  }
  if (typeof value === "object" && value && "colorSpace" in value)
    return (
      "#" +
      (value as unknown as { components: number[] }).components
        .map((c) =>
          Math.round(c * 255)
            .toString(16)
            .padStart(2, "0"),
        )
        .join("")
        .toUpperCase()
    );
  if (Array.isArray(value))
    return value.map((v) => (v === "sans-serif" ? v : `"${v}"`)).join(", ");
  if (typeof value === "object" && value) {
    const d = value as { value: number; unit: string };
    return `${d.value}${d.unit}`;
  }
  return String(value);
}
const variables: string[] = [],
  theme: string[] = [];
const namespaces: Record<string, string> = {
  aspectRatio: "aspect",
  color: "color",
  space: "spacing",
  radius: "radius",
  size: "spacing",
  fontSize: "text",
  lineHeight: "leading",
  fontFamily: "font",
  motionDuration: "transition-duration",
  motionEasing: "ease",
};
for (const [group, tokens] of Object.entries(source.semantic)) {
  for (const [name, token] of Object.entries(tokens as Record<string, Token>)) {
    const key = `--ds-${group}-${name}`;
    variables.push(`  ${key}: ${resolve(token.$value)};`);
    theme.push(`  --${namespaces[group]}-${name}: var(${key});`);
    if (group === "fontSize")
      theme.push(
        `  --text-${name}--line-height: var(--ds-lineHeight-${name});`,
      );
  }
}
writeFileSync(
  "src/ds/tokens/tokens.css",
  `/* Generated by npm run tokens. Do not edit. */\n:root {\n${variables.join("\n")}\n}\n`,
);
writeFileSync(
  "src/ds/tokens/theme.css",
  `/* Generated by npm run tokens. Do not edit. */\n@theme {\n  --*: initial;\n${theme.join("\n")}\n}\n`,
);

const samples: string[] = [];
for (const name of Object.keys(source.semantic.color))
  samples.push(`.ds-swatch--${name} { background: var(--ds-color-${name}); }`);
for (const name of Object.keys(source.semantic.space))
  samples.push(`.ds-space-sample--${name} { width: var(--ds-space-${name}); }`);
for (const name of Object.keys(source.semantic.fontSize))
  samples.push(
    `.ds-type-sample--${name} { font-size: var(--ds-fontSize-${name}); line-height: var(--ds-lineHeight-${name}); }`,
  );
writeFileSync(
  "src/ds/tokens/catalog.css",
  `/* Generated by npm run tokens. Do not edit. */\n${samples.join("\n")}\n`,
);
