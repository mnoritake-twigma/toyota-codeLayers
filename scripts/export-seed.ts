import { mkdirSync, writeFileSync } from "node:fs";
const names =
  "北海道 青森県 岩手県 宮城県 秋田県 山形県 福島県 茨城県 栃木県 群馬県 埼玉県 千葉県 東京都 神奈川県 新潟県 富山県 石川県 福井県 山梨県 長野県 岐阜県 静岡県 愛知県 三重県 滋賀県 京都府 大阪府 兵庫県 奈良県 和歌山県 鳥取県 島根県 岡山県 広島県 山口県 徳島県 香川県 愛媛県 高知県 福岡県 佐賀県 長崎県 熊本県 大分県 宮崎県 鹿児島県 沖縄県".split(
    " ",
  );
const prefectures = names.map((name, i) => ({
  code: String(i + 1).padStart(2, "0"),
  name,
}));
const modelNames = [
  "AURA",
  "TERRA",
  "VELA",
  "ÉLAN",
  "NOVA",
  "MIRA",
  "SÉREIN",
  "CLARA",
  "LYRA",
  "ESPACE",
];
const models = modelNames.map((name, i) => ({
  code: `M${String(i + 1).padStart(2, "0")}`,
  name,
  category: i < 6 ? "SUV" : i < 9 ? "SEDAN" : "MPV",
  tagline: [
    "静けさと、力強さを。",
    "日常の先へ、心のままに。",
    "上質な時間を、ともに。",
  ][i % 3],
}));
const centers: Record<string, [number, number]> = {
  "13": [35.68, 139.76],
  "14": [35.45, 139.64],
  "23": [35.18, 136.91],
  "27": [34.69, 135.5],
};
const dealers = prefectures.flatMap((p, i) =>
  Array.from(
    {
      length:
        ({ "13": 24, "14": 16, "23": 12, "27": 16 } as Record<string, number>)[
          p.code
        ] ?? (i < 4 ? 1 : 2),
    },
    (_, j) => {
      const [lat, lng] = centers[p.code] ?? [26 + i * 0.35, 128 + i * 0.25];
      return {
        id: `${p.code}-${String(j + 1).padStart(3, "0")}`,
        code: `D${p.code}${String(j + 1).padStart(3, "0")}`,
        prefecture_code: p.code,
        name: `LUMIÈRE ${["月白", "朝凪", "星見", "風庭", "光丘", "水葉"][j % 6]}${String(j + 1).padStart(2, "0")}`,
        address: `${p.name} ひかり市${["月白", "朝凪", "星見"][j % 3]}町${j + 1}丁目1番（架空）`,
        postal_code: `${p.code}0${String(j + 1).padStart(4, "0")}`,
        lat: lat + ((j % 5) - 2) * 0.025,
        lng: lng + (Math.floor(j / 5) - 2) * 0.03,
        phone: "000-0000-0000",
        business_hours: "10:00–18:00（火曜日定休）",
      };
    },
  ),
);
const dealer_test_cars = dealers.flatMap((d, i) =>
  models
    .filter((_, m) => (i + m) % 10 >= 3)
    .map((m) => ({ dealer_id: d.id, model_code: m.code })),
);
// デモ用の先頭3桁→代表座標。実在の郵便番号住所検索ではありません。
const postal_centers: Record<string, { lat: number; lng: number }> = {};
for (const d of dealers)
  postal_centers[d.postal_code.slice(0, 3)] ??= { lat: d.lat, lng: d.lng };
for (const prefix of ["100", "101", "150", "160"])
  postal_centers[prefix] = { lat: 35.68, lng: 139.76 };
postal_centers["220"] = { lat: 35.45, lng: 139.64 };
postal_centers["530"] = { lat: 34.69, lng: 135.5 };
postal_centers["450"] = { lat: 35.18, lng: 136.91 };
mkdirSync("src/data/seed", { recursive: true });
mkdirSync("supabase/functions/_shared", { recursive: true });
for (const [name, data] of Object.entries({
  models,
  prefectures,
  dealers,
  dealer_test_cars,
  postal_centers,
}))
  writeFileSync(
    `src/data/seed/${name}.json`,
    JSON.stringify(data, null, 2) + "\n",
  );
writeFileSync(
  "supabase/functions/_shared/postal-centers.json",
  JSON.stringify(postal_centers, null, 2) + "\n",
);
const quote = (v: unknown) =>
  typeof v === "number" ? String(v) : `'${String(v).replaceAll("'", "''")}'`;
const sql = [models, prefectures, dealers, dealer_test_cars]
  .map((rows, i) => {
    const columns = Object.keys(rows[0]);
    return `insert into public.${["models", "prefectures", "dealers", "dealer_test_cars"][i]} (${columns.join(",")}) values\n${rows.map((r) => "(" + columns.map((c) => quote((r as unknown as Record<string, unknown>)[c])).join(",") + ")").join(",\n")}\non conflict do nothing;`;
  })
  .join("\n\n");
writeFileSync(
  "supabase/seed.sql",
  "-- Generated by npm run seed:export. All dealer identities are fictional.\n" +
    sql +
    "\n",
);
console.log(
  `${models.length} models / ${prefectures.length} prefectures / ${dealers.length} dealers / ${dealer_test_cars.length} registrations`,
);
